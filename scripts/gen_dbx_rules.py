#!/usr/bin/env python3
"""Generate Booto's UEFI dbx rules from Microsoft's published dbx list.

Input:  rules/sources/dbx_info_msft_latest.json, a copy of
        https://github.com/microsoft/secureboot_objects/blob/main/PreSignedObjects/DBX/dbx_info_msft_latest.json
        (BSD-2-Clause-Patent; notice in rules/sources/secureboot_objects-License.txt).
Output: the rules JSON (uefi_dbx_revocations.json) and, optionally, the C include that
        src/rules_loader.c uses as its built-in table. Both come from the same entries, so
        the built-in table and the rules file stay identical (tests/test_rules_loader.c).

Offline and deterministic: same input, same bytes. Standard library only.
"""
import json
import re
import sys

# Field capacities in rules_dbx_entry_t (include/rules_loader.h), minus the NUL.
THREAT_MAX, CVE_MAX, DESC_MAX = 95, 31, 159
ARCH_ORDER = ("x64", "ia32", "aarch64", "arm")
CVE_RE = re.compile(r"CVE-\d{4}-\d{4,7}")


def clean(text, cap):
    """Printable ASCII without quotes or backslashes, so JSON and C need no escaping."""
    text = "".join(c if " " <= c <= "~" and c not in "\"\\" else " " for c in text or "")
    text = " ".join(text.split())
    return text if len(text) <= cap else text[: cap - 3].rstrip() + "..."


def entries(src):
    seen = set()
    for arch in ARCH_ORDER:
        for img in src["images"].get(arch, []):
            if img.get("hashType", "SHA256") != "SHA256":
                continue
            sha = img["authenticodeHash"].lower()
            if not re.fullmatch(r"[0-9a-f]{64}", sha) or sha in seen:
                continue
            seen.add(sha)
            desc = img.get("description", "")
            cve = CVE_RE.search(desc)
            company = img.get("companyName", "")
            parts = ["In dbx since " + img.get("dateOfAddition", "unknown date"), "arch " + arch]
            if company and company != "Unknown":
                parts.append("vendor " + company)
            parts.append(desc.strip() or "no reason published by Microsoft")
            filename = img.get("filename", "")
            yield {
                "sha256": sha,
                "threat": clean("Revoked boot binary: " + filename if filename else "Revoked boot binary", THREAT_MAX),
                "cve": cve.group(0) if cve else "",
                "severity": "HIGH",
                "description": clean("; ".join(parts) + ".", DESC_MAX),
            }


def main(argv):
    if len(argv) not in (3, 4):
        sys.exit("usage: gen_dbx_rules.py <dbx_info_msft_latest.json> <out.json> [out.inc]")
    with open(argv[1], encoding="utf-8") as f:
        rules = list(entries(json.load(f)))
    with open(argv[2], "w", encoding="ascii", newline="\n") as f:
        json.dump({"revocations": rules}, f, indent=2)
        f.write("\n")
    if len(argv) == 4:
        with open(argv[3], "w", encoding="ascii", newline="\n") as f:
            f.write("/* Generated by scripts/gen_dbx_rules.py from Microsoft's dbx list; do not edit. */\n")
            for r in rules:
                f.write('{ "%s", "%s", "%s", "%s", "%s" },\n'
                        % (r["sha256"], r["threat"], r["cve"], r["severity"], r["description"]))
    print(len(rules))


if __name__ == "__main__":
    main(sys.argv)
